import * as fs from 'fs';
import * as path from 'path';
import { pageCardCatalog } from './page-card-catalog';

const output = path.resolve(__dirname, '../../../../../docs/postman');
fs.mkdirSync(output, { recursive: true });
const makeRequest = (name: string, endpoint: string, expected: number, cardId?: string) => ({
  name,
  request: { method: 'GET', header: [], url: `{{baseUrl}}${endpoint}` },
  event: [{ listen: 'test', script: { type: 'text/javascript', exec: [
    `pm.test('HTTP ${expected}', function () { pm.response.to.have.status(${expected}); });`,
    ...(expected === 200 && cardId ? [
      `pm.test('Correct card', function () { pm.expect(pm.response.json().data.cardId).to.eql(${JSON.stringify(cardId)}); });`,
      "pm.test('Source metadata', function () { pm.expect(pm.response.json().meta.tables).to.be.an('array').that.is.not.empty; });",
    ] : []),
  ] } }],
});
const folders = pageCardCatalog.map(page => ({
  name: page.title,
  item: [
    makeRequest('Card catalog', `/pages/${page.id}/cards`, 200),
    ...page.cards.map(card => ({
      ...makeRequest(card.title, `/pages/${page.id}/cards/${card.id}${card.query?.filters.includes('date') ? '?date=2026-11-21' : ''}`,
        card.query ? 200 : 501, card.id),
      description: card.query ? `Tables: ${card.query.tables.join(', ')}. Accepted filters: ${card.query.filters.join(', ') || 'none'}. Coverage: ${card.query.coverage}.` : card.unavailableReason,
    })),
  ],
}));
const collection = {
  info: {
    name: 'EduAtlas — QA per Page and Card',
    schema: 'https://schema.getpostman.com/json/collection/v2.1.0/collection.json',
    description: 'Generated from the runtime card catalog. Known unavailable cards intentionally assert HTTP 501. No database writes.',
  },
  variable: [{ key: 'baseUrl', value: 'http://localhost:4000/api/v1', type: 'string' }],
  item: [
    makeRequest('All pages and cards', '/pages', 200),
    ...folders,
    { name: 'Negative cases', item: [
      makeRequest('Unknown page', '/pages/missing/cards', 404),
      makeRequest('Unknown card', '/pages/overview/cards/missing', 404),
      makeRequest('Unsupported period on current aggregate', '/pages/overview/cards/total-schools?year=2026', 400),
      makeRequest('Invalid limit', '/pages/data-explorer/cards/schools-table?limit=101', 400),
      makeRequest('Invalid date', '/pages/calendar/cards/agenda-today?date=2026-02-30', 400),
    ] },
  ],
};
fs.writeFileSync(path.join(output, 'page-cards.postman_collection.json'), `${JSON.stringify(collection, null, 2)}\n`);
const count = pageCardCatalog.reduce((total, page) => total + page.cards.length, 0);
const supported = pageCardCatalog.reduce((total, page) => total + page.cards.filter(card => card.query).length, 0);
const lines = [
  '# Endpoint matrix per page and card', '',
  `Generated by yarn qa:cards:export. ${pageCardCatalog.length} pages, ${count} cards: ${supported} supported and ${count - supported} unavailable.`, '',
  'URLs below are relative to API_PREFIX (default /api/v1). Supported cards return 200; unavailable cards return 501 with an explicit reason. See [card QA guide](../page-card-qa.md).', '',
];
for (const page of pageCardCatalog) {
  lines.push(`## ${page.title}`, '', `Sidebar: ${page.sidebarPath}`, '',
    '| Card | GET endpoint | Status | Filters | Source / reason |', '|---|---|---:|---|---|');
  for (const card of page.cards) {
    lines.push(`| ${card.title} | /pages/${page.id}/cards/${card.id} | ${card.query ? 200 : 501} | ${card.query?.filters.join(', ') || '—'} | ${card.query?.tables.join(', ') ?? card.unavailableReason} |`);
  }
  lines.push('');
}
fs.writeFileSync(path.join(output, 'page-card-endpoints.md'), `${lines.join('\n')}\n`);
console.log(`Exported ${count} cards (${supported} supported) across ${pageCardCatalog.length} pages to ${output}`);
